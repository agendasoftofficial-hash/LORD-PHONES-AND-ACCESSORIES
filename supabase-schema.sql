create or replace function public.complete_sale(
  p_receipt_no text,
  p_customer_id bigint,
  p_cashier_id uuid,
  p_subtotal numeric,
  p_discount numeric,
  p_total numeric,
  p_payment_method text,
  p_payment_reference text,
  p_items jsonb
)
returns public.sales
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sale public.sales;
  v_item jsonb;
  v_phone public.phone_units;
  v_product public.products;
  v_qty integer;
  v_product_id bigint;
  v_imei text;
begin
  -- Create the sale first; all following work is part of the same transaction.
  insert into public.sales (
    receipt_no, customer_id, cashier_id, subtotal, discount, total,
    payment_method, payment_reference
  )
  values (
    p_receipt_no, p_customer_id, p_cashier_id, p_subtotal, p_discount, p_total,
    p_payment_method, nullif(trim(coalesce(p_payment_reference, '')), '')
  )
  returning * into v_sale;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_qty := greatest(1, coalesce((v_item->>'quantity')::integer, 1));
    v_product_id := nullif(v_item->>'product_id', '')::bigint;
    v_imei := nullif(trim(v_item->>'imei'), '');

    -- A phone unit is always sold as exactly one physical device.
    if v_imei is not null then
      if v_qty <> 1 then
        raise exception 'A phone IMEI can only be sold as quantity 1';
      end if;

      select *
      into v_phone
      from public.phone_units
      where imei_1 = v_imei
         or imei_2 = v_imei
      for update;

      if not found then
        raise exception 'IMEI % was not found', v_imei;
      end if;

      if v_phone.status <> 'In Stock' then
        raise exception 'IMEI % is already %', v_imei, v_phone.status;
      end if;

      insert into public.sale_items (
        sale_id, product_id, product_name, imei, quantity, unit_price, line_total
      )
      values (
        v_sale.id,
        v_phone.product_id,
        concat_ws(' ', v_phone.brand, v_phone.model),
        v_imei,
        1,
        v_phone.selling_price,
        v_phone.selling_price
      );

      update public.phone_units
      set status = 'Sold',
          sold_at = now(),
          sale_id = v_sale.id
      where id = v_phone.id;

    else
      -- Normal stock item / accessory.
      if v_product_id is null then
        raise exception 'A sale item must have a product_id or IMEI';
      end if;

      select *
      into v_product
      from public.products
      where id = v_product_id
      for update;

      if not found then
        raise exception 'Product % was not found', v_product_id;
      end if;

      if v_product.stock < v_qty then
        raise exception 'Not enough stock for %. Available: %, requested: %',
          v_product.name, v_product.stock, v_qty;
      end if;

      insert into public.sale_items (
        sale_id, product_id, product_name, imei, quantity, unit_price, line_total
      )
      values (
        v_sale.id,
        v_product.id,
        v_product.name,
        null,
        v_qty,
        v_product.price,
        v_product.price * v_qty
      );

      update public.products
      set stock = stock - v_qty
      where id = v_product.id;
    end if;
  end loop;

  return v_sale;
end;
$$;

grant execute on function public.complete_sale(
  text, bigint, uuid, numeric, numeric, numeric, text, text, jsonb
) to authenticated;
