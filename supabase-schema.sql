create table if not exists public.phone_units (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete set null,
  brand text not null,
  model text not null,
  storage text,
  ram text,
  color text,
  condition text not null default 'New' check (condition in ('New','Used','Refurbished')),
  imei_1 text not null unique,
  imei_2 text unique,
  cost numeric(12,2) not null default 0,
  selling_price numeric(12,2) not null default 0,
  supplier text,
  purchase_date date,
  warranty text,
  status text not null default 'In Stock' check (status in ('In Stock','Reserved','Sold','Returned')),
  sold_at timestamptz,
  sale_id bigint references public.sales(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists phone_units_imei_1_idx on public.phone_units (imei_1);
create index if not exists phone_units_imei_2_idx on public.phone_units (imei_2);
create index if not exists phone_units_status_idx on public.phone_units (status);

alter table public.phone_units enable row level security;

drop policy if exists "Authenticated users can view phone units" on public.phone_units;
create policy "Authenticated users can view phone units"
on public.phone_units for select to authenticated using (true);

drop policy if exists "Authenticated users can manage phone units" on public.phone_units;
create policy "Authenticated users can manage phone units"
on public.phone_units for all to authenticated
using (true) with check (true);

create or replace function public.find_phone_by_imei(p_imei text)
returns setof public.phone_units
language sql
security definer
set search_path = public
as $$
  select *
  from public.phone_units
  where imei_1 = trim(p_imei)
     or imei_2 = trim(p_imei)
  limit 1;
$$;

grant execute on function public.find_phone_by_imei(text) to authenticated;

create or replace function public.sell_phone_unit(
  p_imei text,
  p_sale_id bigint
)
returns public.phone_units
language plpgsql
security definer
set search_path = public
as $$
declare
  v_unit public.phone_units;
begin
  select *
    into v_unit
  from public.phone_units
  where imei_1 = trim(p_imei)
     or imei_2 = trim(p_imei)
  for update;

  if not found then
    raise exception 'IMEI % was not found', p_imei;
  end if;

  if v_unit.status <> 'In Stock' then
    raise exception 'IMEI % is already %', p_imei, v_unit.status;
  end if;

  update public.phone_units
  set status = 'Sold', sold_at = now(), sale_id = p_sale_id
  where id = v_unit.id
  returning * into v_unit;

  return v_unit;
end;
$$;

grant execute on function public.sell_phone_unit(text,bigint) to authenticated;

