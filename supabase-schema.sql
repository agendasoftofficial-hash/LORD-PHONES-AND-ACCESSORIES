create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'cashier' check (role in ('owner','admin','cashier','inventory','technician')),
  phone text,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'Accessories',
  sku text unique,
  barcode text unique,
  brand text,
  model text,
  color text,
  storage text,
  ram text,
  condition text default 'New',
  imei_1 text unique,
  imei_2 text unique,
  price numeric(12,2) not null default 0,
  cost numeric(12,2) not null default 0,
  stock integer not null default 0,
  warranty text,
  supplier text,
  created_at timestamptz not null default now()
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  email text,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  receipt_no text unique not null,
  customer_id bigint references public.customers(id) on delete set null,
  cashier_id uuid references auth.users(id) on delete set null,
  subtotal numeric(12,2) not null default 0,
  discount numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  payment_method text not null default 'Cash',
  payment_reference text,
  created_at timestamptz not null default now()
);

create table if not exists public.sale_items (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  imei text,
  quantity integer not null default 1,
  unit_price numeric(12,2) not null default 0,
  line_total numeric(12,2) not null default 0
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  description text not null,
  category text,
  amount numeric(12,2) not null default 0,
  expense_date date not null default current_date,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.repairs (
  id bigint generated by default as identity primary key,
  job_no text unique not null,
  customer_id bigint references public.customers(id) on delete set null,
  device text not null,
  imei text,
  fault text,
  technician_id uuid references auth.users(id) on delete set null,
  status text not null default 'Received',
  repair_cost numeric(12,2) not null default 0,
  notes text,
  created_at timestamptz not null default now()
);

create or replace function public.decrement_product_stock(p_product_id bigint, p_quantity integer)
returns void
language plpgsql
security invoker
as $$
begin
  update public.products
  set stock = greatest(stock - p_quantity, 0)
  where id = p_product_id;
end;
$$;

