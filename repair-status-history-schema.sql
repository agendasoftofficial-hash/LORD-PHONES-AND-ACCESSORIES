-- G-LOKOO POS v1.2.1 - Repair Status History
-- Run after repairs-schema.sql.

create table if not exists public.repair_status_history (
  id bigint generated by default as identity primary key,
  repair_id bigint not null references public.repairs(id) on delete cascade,
  old_status text,
  new_status text not null,
  changed_by uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);

alter table public.repair_status_history enable row level security;

drop policy if exists "repair status history read" on public.repair_status_history;
create policy "repair status history read"
on public.repair_status_history for select to authenticated
using (public.is_management() or changed_by=auth.uid());

drop policy if exists "repair status history insert" on public.repair_status_history;
create policy "repair status history insert"
on public.repair_status_history for insert to authenticated
with check (public.current_user_role() in ('owner','admin','technician'));

create or replace function public.audit_repair_status_change()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if new.status is distinct from old.status then
    insert into public.repair_status_history(repair_id,old_status,new_status,changed_by)
    values(new.id,old.status,new.status,auth.uid());
  end if;
  return new;
end;
$$;

drop trigger if exists trg_audit_repair_status_change on public.repairs;
create trigger trg_audit_repair_status_change
after update of status on public.repairs
for each row execute procedure public.audit_repair_status_change();

grant select on public.repair_status_history to authenticated;
grant insert on public.repair_status_history to authenticated;
