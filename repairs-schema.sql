alter table public.repairs add column if not exists amount_paid numeric(12,2) not null default 0;
alter table public.repairs add column if not exists balance_due numeric(12,2) not null default 0;
alter table public.repairs add column if not exists payment_status text not null default 'No Charge';
alter table public.repairs add column if not exists due_date date;
alter table public.repairs add column if not exists completed_at timestamptz;
alter table public.repairs add column if not exists updated_at timestamptz not null default now();

update public.repairs
set balance_due=greatest(coalesce(repair_cost,0)-coalesce(amount_paid,0),0),
    payment_status=case when coalesce(repair_cost,0)=0 then 'No Charge' when coalesce(amount_paid,0)>=coalesce(repair_cost,0) then 'Paid' when coalesce(amount_paid,0)>0 then 'Part Payment' else 'Credit' end
where true;

create table if not exists public.repair_payments (
  id bigint generated by default as identity primary key,
  repair_id bigint not null references public.repairs(id) on delete cascade,
  amount numeric(12,2) not null check (amount>0),
  payment_method text not null default 'Cash',
  reference text,
  received_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
alter table public.repair_payments enable row level security;

drop policy if exists "repair payments read" on public.repair_payments;
create policy "repair payments read" on public.repair_payments for select to authenticated using (public.is_management() or received_by=auth.uid());
drop policy if exists "repair payments insert" on public.repair_payments;
create policy "repair payments insert" on public.repair_payments for insert to authenticated with check (public.current_user_role() in ('owner','admin','technician'));

create or replace function public.record_repair_payment(
  p_repair_id bigint,
  p_amount numeric,
  p_method text default 'Cash',
  p_reference text default null
) returns public.repairs
language plpgsql security invoker
set search_path=public
as $$
declare r public.repairs;
begin
  if p_amount is null or p_amount <= 0 then raise exception 'Payment amount must be greater than zero'; end if;
  select * into r from public.repairs where id=p_repair_id for update;
  if not found then raise exception 'Repair job not found'; end if;
  if p_amount > coalesce(r.balance_due,0) then raise exception 'Payment exceeds the outstanding repair balance'; end if;

  insert into public.repair_payments(repair_id,amount,payment_method,reference,received_by)
  values(p_repair_id,p_amount,p_method,nullif(trim(p_reference),''),auth.uid());

  update public.repairs
  set amount_paid=coalesce(amount_paid,0)+p_amount,
      balance_due=greatest(coalesce(balance_due,0)-p_amount,0),
      payment_status=case when greatest(coalesce(balance_due,0)-p_amount,0)=0 then 'Paid' else 'Part Payment' end,
      updated_at=now()
  where id=p_repair_id
  returning * into r;
  return r;
end;
$$;

grant execute on function public.record_repair_payment(bigint,numeric,text,text) to authenticated;

create or replace function public.set_repairs_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at=now(); return new; end; $$;
drop trigger if exists trg_repairs_updated_at on public.repairs;
create trigger trg_repairs_updated_at before update on public.repairs for each row execute procedure public.set_repairs_updated_at();

